#include <iostream>
int main() {
    // while loop - loop until ...
    // you can add bool yourBool = true here
    while (true) { // you can replace 'true' with yourBool. Like: while (yourBool)
        int score = 999;
        if (score == 999) {
            break; // exit loop, if you don't have, program will never ends.
        }
    }
    return 0;
}
